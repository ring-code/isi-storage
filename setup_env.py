import os
import secrets
import getpass
from pathlib import Path

# --- Configuration ---
STORAGE_ENV_FILE = ".env"
SECRETS_DIR = "secrets"

def generate_secret(length=32):
    """Generates a cryptographically secure hex string."""
    return secrets.token_hex(length)

def prompt_for_input(prompt_text, default=None, allow_empty=False):
    """
    Asks the user for input with an optional default value.
    If allow_empty is True, the user can just press Enter to return an empty string.
    """
    if default:
        return input(f"{prompt_text} [default: {default}]: ") or default
    else:
        while True:
            value = input(f"{prompt_text}: ")
            if value:
                return value
            if allow_empty:
                return ""
            print("This field cannot be empty. Please try again.")

def prompt_for_password(prompt_text):
    """Asks the user for a password securely without echoing it to the console."""
    while True:
        password = getpass.getpass(f"{prompt_text}: ")
        if password:
            return password
        print("Password cannot be empty. Please try again.")

def write_file(filepath, content):
    """Writes content to a file, overwriting if it exists."""
    with open(filepath, 'w') as f:
        f.write(content)
    print(f"✅ Successfully created {filepath}")

def main():
    print("--- Welcome to the ISI Storage Setup Wizard ---")
    print("This will generate the .env file for your storage backend.")

    if os.path.exists(STORAGE_ENV_FILE):
        print(f"\n⚠️  WARNING: An existing '{STORAGE_ENV_FILE}' file was found.")
        confirm = input("Running this will overwrite it. Are you sure you want to continue? (yes/no): ")
        if confirm.lower() != 'yes':
            print("Setup cancelled.")
            return

    Path(SECRETS_DIR).mkdir(exist_ok=True)

    print("\n--- [1/3] Please provide the necessary information ---")
    
    wp_domain = prompt_for_input("Enter the public domain of the WordPress site (optional, press Enter to skip. No URL will turn off polling for orders.)", allow_empty=True)   
    admin_email = prompt_for_input("Enter the email for the default Storage admin user", "admin@test.com")
    admin_user = prompt_for_input("Enter the username for the default Storage admin user", "admin")
    admin_password = prompt_for_password("Enter a strong password for the Storage admin user. Change this immediately after login.")

    print("\n--- [2/3] Generating secure random secrets... ---")
    storage_secret_key = generate_secret()
    postgres_password = generate_secret()
    isi_sync_api_key = generate_secret(48)
    print("Secrets generated.")

    # Write Secrets to individual files
    write_file(f"{SECRETS_DIR}/default_admin_password.txt", admin_password)
    write_file(f"{SECRETS_DIR}/storage_secret_key.txt", storage_secret_key)
    write_file(f"{SECRETS_DIR}/postgres_password.txt", postgres_password)
    write_file(f"{SECRETS_DIR}/isi_sync_api_key.txt", isi_sync_api_key)
    print("✅ Secrets securely written to /secrets directory.")

    if wp_domain:
        wp_api_base_url = f"https://{wp_domain}/wp-json/isi/v1"
    else:
        wp_api_base_url = ""

    storage_env_content = f"""
# This file was auto-generated by setup.py

# --- Default Storage Admin Credentials ---
DEFAULT_ADMIN_EMAIL={admin_email}
DEFAULT_ADMIN_USER={admin_user}

# --- API URLs (Optional)---
# The base URL of the WordPress installation's REST API.
WP_API_BASE_URL={wp_api_base_url}
CORS_ORIGINS=


# --- PostgreSQL Config ---
POSTGRES_USER=isidb_user
POSTGRES_DB=storage_db


"""

    print("\n--- [3/3] Writing configuration file... ---")
    write_file(STORAGE_ENV_FILE, storage_env_content.strip())
    
    print("\n🎉 Setup complete!")
    print(f"The '{STORAGE_ENV_FILE}' file has been created.")
    print("You can now run 'docker compose up -d' to start the storage service.")

if __name__ == "__main__":
    main()